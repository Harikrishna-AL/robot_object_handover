"""Build xarm7_4f.urdf: the hand subtree of gen3_4f.urdf, unchanged, mounted on
UFactory's xArm7 (from xarm_ros2/xarm_description, model_num=0) in place of the GEN3 arm."""
import copy, sys, xml.etree.ElementTree as ET
gen3_path, xarm_path, out_path = sys.argv[1:4]
g = ET.parse(gen3_path).getroot()
x = ET.parse(xarm_path).getroot()

GEN3_ARM_LINKS = {"base_link", "shoulder_link", "half_arm_1_link", "half_arm_2_link", "forearm_link",
                  "spherical_wrist_1_link", "spherical_wrist_2_link", "bracelet_link", "end_effector_link"}
GEN3_ARM_JOINTS = {"base_joint", "arm_joint_1", "arm_joint_2", "arm_joint_3", "arm_joint_4", "arm_joint_5",
                   "arm_joint_6", "arm_joint_7", "end_effector", "tool_frame_joint"}

out = ET.Element("robot", {"name": "xarm7_4f"})
out.append(ET.Comment(
    " Generated by build_xarm7_4f.py. Arm: UFactory xArm7 (xarm_ros2 xarm_description, model_num=0, BSD-3). "
    "Hand + contact links + palm_2_ur mount: copied unchanged from gen3_4f.urdf. "
    "xArm joints renamed joint1..7 -> arm_joint_1..7 so the task config's joint names still apply. "))
# keep materials and anything else top-level from gen3 that is not an arm link/joint
for el in g:
    if el.tag == "link" and el.get("name") in GEN3_ARM_LINKS: continue
    if el.tag == "joint" and el.get("name") in GEN3_ARM_JOINTS: continue
    if el.tag in ("transmission", "gazebo", "ros2_control"): continue   # sim-irrelevant, may name GEN3 parts
    out.append(copy.deepcopy(el))
names = {el.get("name") for el in out if el.tag == "link"}
assert "world" in names and "tool_frame" in names and "hand_palm_link" in names, names

for el in x:
    if el.tag == "link":
        out.append(copy.deepcopy(el))
    elif el.tag == "joint":
        j = copy.deepcopy(el)
        if j.get("name").startswith("joint"):
            j.set("name", "arm_joint_" + j.get("name")[len("joint"):])
        out.append(j)

def fixed(name, parent, child, xyz="0 0 0", rpy="0 0 0"):
    j = ET.SubElement(out, "joint", {"name": name, "type": "fixed"})
    ET.SubElement(j, "parent", {"link": parent}); ET.SubElement(j, "child", {"link": child})
    ET.SubElement(j, "origin", {"xyz": xyz, "rpy": rpy})
fixed("base_joint", "world", "link_base")
# xArm7's link7 frame is the tool flange (UFactory's link_eef is a zero-offset fixed child of link7),
# with +z pointing out of the flange -- the same convention as GEN3's tool_frame, which palm_2_ur relies on.
fixed("tool_frame_joint", "link7", "tool_frame")

# meshes: point at the copies under config/meshes/xarm, relative like the hand's
for m in out.iter("mesh"):
    f = m.get("filename")
    if f.startswith("MESHROOT/"):
        m.set("filename", "./../meshes/xarm/" + f[len("MESHROOT/"):])

ET.indent(out, space="  ")
ET.ElementTree(out).write(out_path, xml_declaration=True, encoding="utf-8")

# sanity: single tree rooted at world, every joint's parent/child exist, no duplicate names
links = [l.get("name") for l in out.findall("link")]
joints = out.findall("joint")
assert len(links) == len(set(links)), "duplicate link names"
children = [j.find("child").get("link") for j in joints]
assert len(children) == len(set(children)), "a link has two parents"
for j in joints:
    for t in ("parent", "child"):
        assert j.find(t).get("link") in links, (j.get("name"), t)
roots = set(links) - set(children)
assert roots == {"world"}, roots
print(f"OK: {len(links)} links, {len(joints)} joints, root=world")
print("arm joints:", [j.get("name") for j in joints if j.get("name").startswith("arm_joint")])
print("hand joints:", sum(1 for j in joints if j.get("type") in ("revolute","continuous") and not j.get("name").startswith("arm_joint")))
